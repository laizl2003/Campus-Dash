ALTER TABLE voucher_stock
  ADD COLUMN status VARCHAR(16) NOT NULL DEFAULT 'ONLINE' COMMENT 'ONLINE / OFFLINE' AFTER stock,
  ADD COLUMN threshold_cents BIGINT NOT NULL DEFAULT 0 COMMENT '满减门槛（分）' AFTER status,
  ADD COLUMN discount_cents BIGINT NOT NULL DEFAULT 0 COMMENT '减免金额（分）' AFTER threshold_cents;

UPDATE voucher_stock SET
  threshold_cents = CASE type
    WHEN 1 THEN 1000 WHEN 2 THEN 1000 WHEN 3 THEN 1000
    WHEN 4 THEN 1500 WHEN 5 THEN 1500 WHEN 6 THEN 1500 WHEN 7 THEN 1500
    WHEN 8 THEN 2000 WHEN 9 THEN 2000
    WHEN 10 THEN 2500 WHEN 11 THEN 2500 ELSE threshold_cents END,
  discount_cents = CASE type
    WHEN 1 THEN 200 WHEN 2 THEN 300 WHEN 3 THEN 500
    WHEN 4 THEN 200 WHEN 5 THEN 300 WHEN 6 THEN 500 WHEN 7 THEN 700
    WHEN 8 THEN 500 WHEN 9 THEN 800
    WHEN 10 THEN 1000 WHEN 11 THEN 1500 ELSE discount_cents END;
